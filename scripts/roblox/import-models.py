#!/usr/bin/env python3
"""Imports 3D models from assets/ into Roblox: glb -> fbx (Blender, headless) -> Open Cloud Model upload. Ids land in
assets/roblox-models.json (key -> {asset, sha, src}); an unchanged source is never re-uploaded. Then writes
src/shared/ModelIds.luau so the game can InsertService:LoadAsset them (the place and the assets share an owner).

Usage: scripts/roblox/import-models.py <list.txt>     lines: <Key> <path/to/model.glb> [ObjectNameInsideFile]
       scripts/roblox/import-models.py --animations build/animations/*.rbxm   KeyframeSequences from
           scripts/roblox/make-animations.luau, uploaded as Animation assets under keys Anim_<FileName>
       scripts/roblox/import-models.py --audio build/sounds/*.wav            sounds (scripts/roblox/make-sounds.py),
           uploaded as Audio assets under keys Sound_<FileName>
       scripts/roblox/import-models.py --luau          only regenerate src/shared/ModelIds.luau
Needs ROBLOX_API_KEY and ROBLOX_USER_ID in scripts/roblox/.env and `blender` on PATH."""
import hashlib
import json
import os
import subprocess
import sys
import tempfile
import time
import urllib.error
import urllib.request
import uuid

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DB = os.path.join(ROOT, "assets", "roblox-models.json")
LUAU = os.path.join(ROOT, "src", "shared", "ModelIds.luau")


def env():
    out = {}
    for line in open(os.path.join(ROOT, "scripts", "roblox", ".env")):
        if "=" in line and not line.startswith("#"):
            k, v = line.strip().split("=", 1)
            out[k] = v.strip().strip('"')
    return out


# Upload kinds: Open Cloud assetType, multipart content type, file extension, description.
KINDS = {
    "Model": ("model/fbx", "fbx", "Floor Defense model (CC0/CC-BY source, see docs/ASSETS.md)"),
    "Animation": ("model/x-rbxm", "rbxm", "Floor Defense weapon animation (authored in scripts/roblox/make-animations.luau)"),
    "Audio": ("audio/wav", "wav", "Floor Defense sound effect (synthesised by scripts/roblox/make-sounds.py)"),
}


def upload(key, user, fbx, name, kind="Model"):
    content_type, ext, description = KINDS[kind]
    meta = {"assetType": kind, "displayName": f"Floor Defense {name}"[:50], "description": description,
            "creationContext": {"creator": {"userId": user}}}
    b = uuid.uuid4().hex
    body = (f'--{b}\r\nContent-Disposition: form-data; name="request"\r\nContent-Type: application/json\r\n\r\n{json.dumps(meta)}\r\n'
            f'--{b}\r\nContent-Disposition: form-data; name="fileContent"; filename="{name}.{ext}"\r\nContent-Type: {content_type}\r\n\r\n').encode()
    body += open(fbx, "rb").read() + f"\r\n--{b}--\r\n".encode()
    req = urllib.request.Request("https://apis.roblox.com/assets/v1/assets", data=body, method="POST",
                                 headers={"x-api-key": key, "Content-Type": f"multipart/form-data; boundary={b}"})
    for attempt in range(5):
        try:
            op = json.loads(urllib.request.urlopen(req, timeout=120).read())
            break
        except urllib.error.HTTPError as e:
            if e.code == 429:  # rate limited: back off
                time.sleep(10 * (attempt + 1))
                continue
            raise SystemExit(f"{name}: upload failed {e.code} {e.read()[:200]}")
    for _ in range(90):
        if op.get("done"):
            break
        time.sleep(2)
        op = json.loads(urllib.request.urlopen(urllib.request.Request(f"https://apis.roblox.com/assets/v1/{op['path']}", headers={"x-api-key": key})).read())
    asset = op.get("response", {}).get("assetId")
    if not asset:
        print(f"{name}: no asset id ({op.get('error')})")
    return asset


def save(db):
    """Writes the id table, keeping entries another import run added to the file meanwhile (runs can overlap)."""
    disk = json.load(open(DB)) if os.path.exists(DB) else {}
    disk.update(db)
    db.update(disk)
    json.dump(db, open(DB, "w"), indent=1, sort_keys=True)


def write_luau(db):
    save(db)
    lines = ["-- GENERATED by scripts/roblox/import-models.py from assets/roblox-models.json. Do not edit by hand.",
             "-- Roblox asset ids: Model ids for the 3D models in assets/ (weapons, creatures, props), loaded with",
             "-- InsertService:LoadAsset on the server; Anim_<Name> Animation ids (scripts/roblox/make-animations.luau) and",
             "-- Sound_<Name> Audio ids (scripts/roblox/make-sounds.py). Keys are the names used by the game modules.", "", "return {"]
    for k in sorted(db):
        lines.append(f'\t["{k}"] = {db[k]["asset"]},')
    lines.append("}")
    open(LUAU, "w").write("\n".join(lines) + "\n")


def upload_files(db, kind, prefix, paths):
    """Uploads ready-made files (animations, sounds) as `kind`, keyed <prefix><file name>; unchanged files are skipped."""
    e = env()
    for path in paths:
        name = prefix + os.path.splitext(os.path.basename(path))[0]
        sha = hashlib.sha256(open(path, "rb").read()).hexdigest()[:16]
        if db.get(name, {}).get("sha") == sha:
            continue
        asset = upload(e["ROBLOX_API_KEY"], e["ROBLOX_USER_ID"], path, name, kind)
        if asset:
            db[name] = {"asset": int(asset), "sha": sha, "src": os.path.relpath(os.path.abspath(path), ROOT)}
            save(db)
            print(f"{name}: {asset}", flush=True)
    write_luau(db)


def main():
    db = json.load(open(DB)) if os.path.exists(DB) else {}
    if sys.argv[1:] == ["--luau"]:
        write_luau(db)
        return
    if sys.argv[1:2] == ["--animations"]:
        upload_files(db, "Animation", "Anim_", sys.argv[2:])
        return
    if sys.argv[1:2] == ["--audio"]:
        upload_files(db, "Audio", "Sound_", sys.argv[2:])
        return
    e = env()
    glb2fbx = os.path.join(ROOT, "scripts", "roblox", "glb2fbx.py")
    tmp = tempfile.mkdtemp(prefix="fd-models-")
    for line in open(sys.argv[1]):
        parts = line.split()
        if not parts or parts[0].startswith("#"):
            continue
        name, src, node = parts[0], parts[1], (parts[2] if len(parts) > 2 else None)
        sha = hashlib.sha256(open(os.path.join(ROOT, src), "rb").read() + (node or "").encode()).hexdigest()[:16]
        if db.get(name, {}).get("sha") == sha:
            continue
        fbx = os.path.join(tmp, name + ".fbx")
        subprocess.run(["blender", "-b", "-noaudio", "--python", glb2fbx, "--", os.path.join(ROOT, src), fbx] + ([node] if node else []),
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=False)
        if not os.path.exists(fbx):
            print(f"{name}: blender conversion failed")
            continue
        asset = upload(e["ROBLOX_API_KEY"], e["ROBLOX_USER_ID"], fbx, name)
        if asset:
            db[name] = {"asset": int(asset), "sha": sha, "src": src + (f"#{node}" if node else "")}
            save(db)
            print(f"{name}: {asset}", flush=True)
    write_luau(db)


if __name__ == "__main__":
    main()
