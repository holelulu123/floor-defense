#!/usr/bin/env python3
"""Generate src/shared/Roster.luau from showcase/catalog.js.

The showcase catalog is the single source of truth for each dungeon's creature roster (which creature
debuts on which wave, its stats, its model) and for each map's theme colours and tower. This script
evaluates catalog.js with node (it is a plain ES module with no imports), dumps the parts the game
needs as JSON, and writes them out as a pure Luau data module that Lune can test.

Usage: scripts/gen-roster.py [--check]
  --check   exit 1 if the committed Roster.luau differs from what would be generated
"""

import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CATALOG = os.path.join(ROOT, "showcase", "catalog.js")
OUT = os.path.join(ROOT, "src", "shared", "Roster.luau")

DUMP = """
import { FAMILIES, MAPS, DUNGEONS } from %s;
const strip = p => (p ?? '').replace(/^(\\.\\.\\/)+/, '');
const base = p => strip(p).split('/').pop().replace(/\\.(glb|gltf)(\\.glb)?$/, '');
const families = FAMILIES.map(f => ({
  id: f.id, name: f.name,
  creatures: f.creatures.map(c => ({
    id: c.id, archetype: c.type, firstWave: c.stats.firstWave, health: c.stats.health, speed: c.stats.speed,
    damage: c.stats.damage, coins: c.stats.coins, scale: c.scale, model: strip(c.model),
    flying: c.type === 'Flyer' || /fly/i.test(c.anims?.idle ?? ''),
  })),
}));
const themes = {};
for (const d of DUNGEONS) {
  const m = MAPS[d.id]; const tower = m.tower ?? m.hall;
  themes[d.id] = { ground: m.ground, path: m.path, sky: m.sky, fog: m.fog, water: m.water ?? null,
    tower: base(tower.file), towerHeight: tower.h, gate: base(m.gate.file), gateHeight: m.gate.h };
}
console.log(JSON.stringify({ families, themes, dungeons: DUNGEONS.map(d => d.id) }));
"""


def luau_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def rgb(hexval):
    return "{ %d, %d, %d }" % ((hexval >> 16) & 255, (hexval >> 8) & 255, hexval & 255)


def num(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int) or float(v).is_integer():
        return str(int(v))
    return repr(float(v))


def generate():
    script = DUMP % json.dumps("file://" + CATALOG)
    out = subprocess.run(["node", "--input-type=module", "-e", script], check=True, capture_output=True, text=True)
    data = json.loads(out.stdout)

    lines = []
    w = lines.append
    w("-- GENERATED by scripts/gen-roster.py from showcase/catalog.js. Do not edit by hand; edit the catalog")
    w("-- and rerun the script. Pure data (no Roblox APIs) so Lune can test it.")
    w("--")
    w("-- One creature roster per family: creatures in the order they debut (firstWave), with the stats")
    w("-- the showcase shows for that debut wave. Waves.luau scales them further per wave and party size.")
    w("")
    w("export type Creature = {")
    w("\tid: string,")
    w("\tarchetype: string, -- key into Enemies.Archetypes (size, colour, behaviour)")
    w("\tfirstWave: number,")
    w("\thealth: number,")
    w("\tspeed: number, -- studs per second")
    w("\tdamage: number, -- dealt to the Town Hall on arrival")
    w("\tcoins: number, -- paid to the killer before the party multiplier")
    w("\tscale: number, -- body size multiplier on the archetype size")
    w("\tmodel: string, -- asset path in the repo; swapped for a MeshPart id once imported")
    w("\tflying: boolean,")
    w("}")
    w("")
    w("export type Theme = {")
    w("\tground: { number },")
    w("\tpath: { number },")
    w("\tsky: { number },")
    w("\tfog: { number },")
    w("\twater: { number }?,")
    w("\ttower: string, -- prop name of the dungeon's tower (the Town Hall)")
    w("\ttowerHeight: number, -- metres in the showcase")
    w("\tgate: string,")
    w("\tgateHeight: number,")
    w("}")
    w("")
    w("local Roster = {}")
    w("")
    w("-- Family id -> ordered creature list. Family ids match Dungeons.luau `family`.")
    w("Roster.Families = {} :: { [string]: { Creature } }")
    w("")
    for fam in data["families"]:
        w("-- %s" % fam["name"])
        w("Roster.Families.%s = {" % fam["id"])
        for c in fam["creatures"]:
            w("\t{")
            w("\t\tid = %s," % luau_str(c["id"]))
            w("\t\tarchetype = %s," % luau_str(c["archetype"]))
            for k in ("firstWave", "health", "speed", "damage", "coins", "scale"):
                w("\t\t%s = %s," % (k, num(c[k])))
            w("\t\tmodel = %s," % luau_str(c["model"]))
            w("\t\tflying = %s," % num(c["flying"]))
            w("\t},")
        w("}")
        w("")
    w("-- Dungeon id -> map theme (colours as RGB 0-255, props by name).")
    w("Roster.Themes = {} :: { [string]: Theme }")
    w("")
    for did in data["dungeons"]:
        t = data["themes"][did]
        w("Roster.Themes.%s = {" % did)
        w("\tground = %s," % rgb(t["ground"]))
        w("\tpath = %s," % rgb(t["path"]))
        w("\tsky = %s," % rgb(t["sky"]))
        w("\tfog = %s," % rgb(t["fog"]))
        if t["water"] is not None:
            w("\twater = %s," % rgb(t["water"]))
        w("\ttower = %s," % luau_str(t["tower"]))
        w("\ttowerHeight = %s," % num(t["towerHeight"]))
        w("\tgate = %s," % luau_str(t["gate"]))
        w("\tgateHeight = %s," % num(t["gateHeight"]))
        w("}")
        w("")
    w("-- Family ids in dungeon unlock order.")
    w("Roster.FamilyOrder = {")
    for fam in data["families"]:
        w("\t%s," % luau_str(fam["id"]))
    w("}")
    w("")
    w("function Roster.family(familyId: string): { Creature }")
    w("\tlocal list = Roster.Families[familyId]")
    w("\tassert(list, `Unknown creature family {familyId}`)")
    w("\treturn list")
    w("end")
    w("")
    w("function Roster.theme(dungeonId: string): Theme")
    w("\tlocal theme = Roster.Themes[dungeonId]")
    w("\tassert(theme, `No theme for dungeon {dungeonId}`)")
    w("\treturn theme")
    w("end")
    w("")
    w("-- Look a creature up by id within a family.")
    w("function Roster.get(familyId: string, creatureId: string): Creature")
    w("\tfor _, c in Roster.family(familyId) do")
    w("\t\tif c.id == creatureId then")
    w("\t\t\treturn c")
    w("\t\tend")
    w("\tend")
    w("\terror(`Unknown creature {creatureId} in family {familyId}`)")
    w("end")
    w("")
    w("return Roster")
    return "\n".join(lines) + "\n"


def main():
    text = generate()
    if "--check" in sys.argv:
        with open(OUT, encoding="utf-8") as f:
            if f.read() != text:
                print("Roster.luau is stale; run scripts/gen-roster.py", file=sys.stderr)
                sys.exit(1)
        print("Roster.luau is up to date")
        return
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
